    why_now = [_spoken_text(value) for value in _unique_text(list(topic.get("why_now") or []))]
    why_channel = [_spoken_text(value) for value in _unique_text(list(topic.get("why_channel") or []))]
    facts = [_spoken_text(value) for value in _unique_text(list(topic.get("facts") or []))]
    unknowns = [_spoken_text(value) for value in _unique_text(list(topic.get("unknowns") or []))]
    source_names = _unique_text(
        [row.get("source_id") for row in list(topic.get("evidence") or [])]
    )
    seed = sum(ord(char) for char in str(topic.get("candidate_id") or title))
    opening = blueprint["openings"][seed % len(blueprint["openings"])]

    source_text = "、".join(source_names) if source_names else "目前公開資料"
    raw_why_now = why_now[0] if why_now else ""
    if "這組事件位於" in raw_why_now or "可與其他頻道共用" in raw_why_now:
        why_now_text = f"最近24到48小時，{source_text}陸續出現與這個主題相關的新資訊。"
    else:
        why_now_text = raw_why_now or "這個主題在最新資料中出現了可核對的新變化。"

    spoken_unknowns = [
        value for value in unknowns if "同一熱點被多頻道採用" not in value
    ]
    topic["why_now"] = why_now
    topic["why_channel"] = why_channel
    topic["facts"] = facts
