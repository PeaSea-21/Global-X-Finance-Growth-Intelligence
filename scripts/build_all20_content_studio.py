def build_payload(
    *,
    site_data: dict[str, Any],
    style_payload: dict[str, Any],
    weekend_payload: dict[str, Any],
) -> dict[str, Any]:
    first_ten = site_data.get("first_ten_workbench")
    if not isinstance(first_ten, dict) or first_ten.get("channel_count") != 10:
        raise ValueError("first-ten workbench is missing or incomplete")
    if weekend_payload.get("status") != "NEWS_CRAWL_PASS":
        raise ValueError("weekend source snapshot is not NEWS_CRAWL_PASS")
    if weekend_payload.get("snapshot_date") != first_ten.get("source_snapshot_date"):
        raise ValueError("first-ten and second-ten source dates do not match")

    styles = list(style_payload.get("channels") or [])
    if tuple(row.get("channel_name") for row in styles) != SECOND_CHANNEL_ORDER:
        raise ValueError("second-ten style pack channel order mismatch")
    topics_by_name = _build_second_topics(list(weekend_payload.get("items") or []))

    second_channels: list[dict[str, Any]] = []
    for style in styles:
        name = style["channel_name"]
        waiting = name in SECOND_WAITING_CHANNELS
        topics = [] if waiting else topics_by_name[name]
        second_channels.append(
            {
                "channel_order": style["channel_order"],
                "channel_id": style["channel_id"],
                "channel_name": name,
                "style_status": style["status"],
                "style_confidence": style["confidence"],
                "content_status": (
                    "WAITING_FOR_TRANSCRIPT_SAMPLES" if waiting else "PROVISIONAL_DRAFT_READY"
                ),
                "content_date": None if waiting else weekend_payload["snapshot_date"],
                "profile_promise": _traditional(style["profile_promise"]),
                "audience": _traditional(style["audience"]),
                "language_style": _traditional(style["language_style"]),
                "opening_hook": _traditional(style["opening_hook"]),
                "narrative_logic": [
                    _traditional(value) for value in style.get("narrative_logic") or []
                ],
                "ending_pattern": _traditional(style["ending_pattern"]),
                "profile_sample_alignment": style["profile_sample_alignment"],
                "reason": _traditional(
                    "尚無完整文稿樣本，語言、開場、敘事與結尾保持UNKNOWN；至少需要2篇完整稿。"
                    if waiting
                    else "依現有稀疏樣本與24/48小時來源生成，等待Ben校準頻道口吻。"
                ),
                "topics": topics,
            }
        )

    channels = json.loads(json.dumps(list(first_ten.get("channels") or []))) + second_channels
    shared_outlines = _build_shared_outline_topics(list(weekend_payload.get("items") or []))
    for channel in channels:
        name = str(channel.get("channel_name") or "")
        program = CHANNEL_PROGRAM_SPECS.get(name)
        if program:
            channel["target_duration"] = program["duration"]
            channel["minimum_script_character_count"] = program["minimum"]
        if name in shared_outlines:
            channel["topics"] = list(channel.get("topics") or []) + shared_outlines[name]
        for topic in list(channel.get("topics") or []):
            _complete_manuscript(name, topic)
