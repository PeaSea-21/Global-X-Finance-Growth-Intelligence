def main() -> int:
    parser = argparse.ArgumentParser(description="Build the all-20 BEN channel workbench.")
    parser.add_argument(
        "--site-data",
        default=str(ROOT / "sites" / "ben-content-studio" / "data.json"),
    )
    parser.add_argument(
        "--style-packs",
        default=str(
            ROOT
            / "research"
            / "ben_radar_second10_style_packs"
            / "style_packs_v0.1.json"
        ),
    )
    parser.add_argument(
        "--weekend-snapshot",
        default=str(
            ROOT
            / "outputs"
            / "ben_weekend_crawl"
            / "2026-08-23"
            / "latest.json"
        ),
    )
    parser.add_argument(
        "--output",
        default=str(
            ROOT
            / "outputs"
            / "ben_all20_editorial"
            / "2026-08-23"
            / "all20_editorial.json"
        ),
    )
    parser.add_argument(
        "--skip-archive-current",
        action="store_true",
        help="Development-only rebuild of the same snapshot; production updates must archive first.",
    )
    args = parser.parse_args()

    site_path = Path(args.site_data)
    site_data = _read_json(site_path)
    previous_workbench = site_data.get("channel_workbench")
    if isinstance(previous_workbench, dict) and not args.skip_archive_current:
        site_data["channel_workbench"] = archive_workbench_channels(
            previous_workbench,
            site_path.parent,
        )
    workbench = build_payload(
        site_data=site_data,
        style_payload=_read_json(Path(args.style_packs)),
        weekend_payload=_read_json(Path(args.weekend_snapshot)),
    )
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(workbench, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    site_data["channel_workbench"] = workbench
    site_path.write_text(
        json.dumps(site_data, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "status": "PASS",
                "channel_count": workbench["channel_count"],
                "draft_ready_channel_count": workbench["draft_ready_channel_count"],
                "waiting_sample_channel_count": workbench["waiting_sample_channel_count"],
                "full_script_count": sum(
                    bool(topic.get("script_text"))
                    for channel in workbench["channels"]
                    for topic in channel.get("topics") or []
                ),
                "output": str(output_path.resolve()),
                "site_data": str(site_path.resolve()),
            },
            ensure_ascii=False,
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
